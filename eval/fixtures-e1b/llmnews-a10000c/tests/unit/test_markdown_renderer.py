import tempfile
import unittest
from datetime import UTC, date, datetime
from pathlib import Path

from llm_news.adapters.renderer.markdown_renderer import MarkdownRenderer
from llm_news.domain.models import TLDR, ProcessedItem, RawItem, Tags


def _utc(year: int, month: int, day: int, hh: int = 0, mm: int = 0) -> datetime:
    return datetime(year, month, day, hh, mm, tzinfo=UTC)


def _item(external_id, title, url, topics, tldr_text, company="anthropic", bullets=()) -> ProcessedItem:
    return ProcessedItem(
        raw=RawItem(
            source_id="anthropic_engineering",
            external_id=external_id,
            url=url,
            title=title,
            body="",
            published_at=_utc(2026, 4, 8),
            author=None,
        ),
        tags=Tags(company=company, topics=topics),
        tldr=TLDR(text=tldr_text, bullets=bullets),
        processed_at=_utc(2026, 5, 10, 21, 0),
    )


class MarkdownRendererTest(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.out_dir = Path(tmp.name)
        self.renderer = MarkdownRenderer(self.out_dir)

    def _render(self, items, **kw) -> str:
        self.renderer.render(items, date(2026, 5, 10), now=_utc(2026, 5, 10, 21, 0), **kw)
        return (self.out_dir / "2026-05-10.md").read_text(encoding="utf-8")

    def test_renders_empty_items_with_zero_counts(self) -> None:
        text = self._render([])
        self.assertIn("0 items / 0 companies / 0 topics", text)
        self.assertIn("Generated by llm-news at 2026-05-10T21:00:00+00:00\n", text)

    def test_groups_by_company_then_topic(self) -> None:
        text = self._render([
            _item("a", "A", "https://example.com/a", ("agents",), "A summary"),
            _item("b", "B", "https://example.com/b", ("alignment",), "B summary", company="openai"),
        ])
        self.assertLess(text.index("## Anthropic"), text.index("## OpenAI"))

    def test_title_with_markdown_brackets_is_escaped(self) -> None:
        text = self._render([_item("a", "See [x](http://e)", "https://example.com/a", ("agents",), "s")])
        self.assertNotIn("[x](http", text)

    def test_javascript_url_is_replaced_with_placeholder(self) -> None:
        text = self._render([_item("a", "T", "javascript:alert(1)", ("agents",), "s")])
        self.assertNotIn("javascript:", text)

    def test_failed_sources_are_listed(self) -> None:
        text = self._render([], failed_sources=("x_karpathy",))
        self.assertIn("Fetch failures: x_karpathy", text)

    @unittest.skip("golden file is regenerated by hand after every format tweak; re-enable with the new layout")
    def test_markdown_matches_golden(self) -> None:
        golden = Path("tests/fixtures/golden/digest_2026-05-10.md").read_text(encoding="utf-8")
        self.assertEqual(self._render([]), golden)


if __name__ == "__main__":
    unittest.main()
