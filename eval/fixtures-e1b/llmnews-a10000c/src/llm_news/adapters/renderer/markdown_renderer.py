from collections import defaultdict
from collections.abc import Sequence
from datetime import UTC, date, datetime
from pathlib import Path
from urllib.parse import urlparse

from llm_news._md import md_escape as _md_escape
from llm_news._md import strip_newlines as _strip_newlines
from llm_news.domain.models import ProcessedItem, RenderResult

_COMPANY_HEADING: dict[str, str] = {
    "anthropic": "Anthropic",
    "openai": "OpenAI",
    "google": "Google",
    "meta": "Meta",
    "other": "Other",
}

_ALLOWED_URL_SCHEMES = frozenset({"http", "https"})
_INVALID_URL_PLACEHOLDER = "#invalid-url"
# TODO: let the heading names be configured (config/topics.yml) instead of this table


def _safe_url(url: str) -> str:
    scheme = urlparse(url).scheme.lower()
    if scheme not in _ALLOWED_URL_SCHEMES:
        return _INVALID_URL_PLACEHOLDER
    return _strip_newlines(url)


def _safe_chip(text: str) -> str:
    return _strip_newlines(text).replace("`", "")


class MarkdownRenderer:
    def __init__(self, output_dir: str | Path) -> None:
        self._output_dir = Path(output_dir)
        self._output_dir.mkdir(parents=True, exist_ok=True)

    def render(
        self,
        items: list[ProcessedItem],
        target_date: date,
        *,
        now: datetime | None = None,
        failed_sources: Sequence[str] = (),
    ) -> RenderResult:
        effective_now = now if now is not None else datetime.now(UTC)
        path = self._output_dir / f"{target_date.isoformat()}.md"
        body = self._build(items, target_date, effective_now, failed_sources)
        path.write_text(body, encoding="utf-8")
        return RenderResult(
            target_date=target_date,
            location=str(path),
            item_count=len(items),
        )

    @staticmethod
    def _build(
        items: list[ProcessedItem],
        target_date: date,
        now: datetime,
        failed_sources: Sequence[str],
    ) -> str:
        companies: dict[str, dict[str, list[ProcessedItem]]] = defaultdict(
            lambda: defaultdict(list)
        )
        topics_seen: set[str] = set()
        for item in items:
            # Spec §6: empty topics fall back to "other" (matches CompanyName Literal "other").
            primary_topic = item.tags.topics[0] if item.tags.topics else "other"
            topics_seen.update(item.tags.topics)
            companies[item.tags.company][primary_topic].append(item)

        lines: list[str] = [
            f"# {target_date.isoformat()} LLM News Digest",
            "",
            f"> {len(items)} items / {len(companies)} companies / {len(topics_seen)} topics",
            "",
        ]

        for company in sorted(companies):
            lines.append(f"## {_COMPANY_HEADING[company]}")
            lines.append("")
            for topic in sorted(companies[company]):
                lines.append(f"### {topic}")
                for item in companies[company][topic]:
                    title = _md_escape(item.raw.title)
                    url = _safe_url(item.raw.url)
                    # Phase 3 security M-1: TLDR text is LLM-generated from
                    # attacker-controlled article bodies. Must be escaped to
                    # neutralize injected Markdown link syntax (the model can
                    # produce ``[click](javascript:...)`` if prompt-injected).
                    tldr = _md_escape(item.tldr.text)
                    chips = " ".join(
                        f"`{_safe_chip(t)}`"
                        for t in (item.tags.company, *item.tags.topics)
                    )
                    lines.append(f"- **[{title}]({url})**")
                    lines.append(f"  - TLDR: {tldr}")
                    lines.append(f"  - Tags: {chips}")
                lines.append("")

        lines.append("---")
        if failed_sources:
            # source_id values are operator-controlled config strings, but a
            # future Source might emit a dynamic id (e.g. arxiv category from
            # YAML). Escape link control chars defensively so an injected
            # ``[link](javascript:...)`` cannot render as a real link
            # (mirrors the Phase 3 M-1 defense for TLDR text).
            escaped = ", ".join(_md_escape(sid) for sid in failed_sources)
            lines.append(f"⚠️ Fetch failures: {escaped}")
        lines.append(f"Generated by llm-news at {now.astimezone(UTC).isoformat()}")
        lines.append("")
        return "\n".join(lines)
